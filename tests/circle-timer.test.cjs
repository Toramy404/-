const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),rows=JSON.parse(fs.readFileSync(path.join(root,'data/circle_timing.json'),'utf8'));
const ctx={window:{}};vm.createContext(ctx);vm.runInContext(fs.readFileSync(path.join(root,'dist/circle-timer.js'),'utf8'),ctx);
const api=ctx.window.NR_TIMER,c=api.clock(rows),start=1_000_000;let count=0;
function eq(actual,expected,label){assert.deepEqual(JSON.parse(JSON.stringify(actual)),expected,label);count++}
let s=c.clean(null);s=c.reduce(s,'toggle',null,start);
eq(c.snapshot(s,start).remaining,270,'new night starts with 4:30 until first shrink');
eq(c.snapshot(s,start+269001).remaining,1,'round positive subsecond remaining up');
eq([c.snapshot(s,start+270000).phase,c.snapshot(s,start+270000).remaining],['第一次收缩中',180],'exact first boundary advances immediately');
eq([c.snapshot(s,start+450000).phase,c.snapshot(s,start+450000).remaining],['圈内探索',210],'first end to second start');
eq([c.snapshot(s,start+660000).phase,c.snapshot(s,start+660000).remaining],['第二次收缩中',180],'second shrink to approximate finish');
eq([c.snapshot(s,start+900000).remaining,c.snapshot(s,start+900000).done,c.snapshot(s,start+900000).running],[0,true,false],'long background gap finishes without negative countdown');
eq(c.snapshot(JSON.parse(JSON.stringify(s)),start+600000).elapsed,600,'reload restores wall-clock elapsed without ticks');
let paused=c.reduce(s,'toggle',null,start+20000);
eq(c.snapshot(paused,start+200000).elapsed,20,'pause does not count background time');
let resumed=c.reduce(paused,'toggle',null,start+200000);
eq(c.snapshot(resumed,start+210000).elapsed,30,'resume accumulates only running time');
let aligned=c.reduce(resumed,'set',320,start+210000);
eq(c.snapshot(aligned,start+211000).elapsed,321,'running calibration reanchors at entered elapsed');
eq(c.snapshot(c.reduce(paused,'adjust',30,start+200000),start+300000).elapsed,50,'paused adjustment stays paused');
eq(c.reduce(paused,'adjust',-999,start).elapsed,0,'negative adjustment clamps at day start');
eq(c.reduce(paused,'set',9999,start).elapsed,840,'large value clamps at end');
eq([c.reduce(resumed,'day',2,start+211000).day,c.reduce(resumed,'day',2,start+211000).elapsed,c.reduce(resumed,'day',2,start+211000).startedAt],[2,0,null],'next night waits for manual start');
eq(c.reduce(s,'reset',null,start+20000),{day:1,elapsed:0,startedAt:null},'reset stops clock');
eq(c.reduce(s,'toggle',null,start+900000).elapsed,0,'completed clock can restart');
eq(c.snapshot(s,start-10000).elapsed,0,'backwards wall clock never yields negative elapsed');
eq(c.parse('05:20'),320,'manual input minutes and seconds');
for(const text of ['5:99','-1:00','14:31','99:00','hello',''])eq(c.parse(text),null,'invalid manual input '+text);
eq(api.format(61),'01:01','display pad');eq(api.format(0),'00:00','finished display');
